print("-----Exercise 2 — Odd / Even-----")      # This program checks if a number is odd or even.
number = int(input("Enter a number: "))      # Take input from the user and convert it to an integer.
if number % 2 == 0:        # Check if the number is divisible by 2.
    print("The number is even.")      # Print that the number is even.
else:                       # Execute if the condition in the if statement is false.
    print("The number is odd.")      # Print that the number is odd.
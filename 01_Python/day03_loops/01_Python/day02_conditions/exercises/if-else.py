print("------IF-ELSE STATEMENT------")      #if-else statement is used to execute a block of code if a specified condition is true, and another block of code if the condition is false.
age = int(input("Enter your age: "))      # Take input from the user and convert it to an integer.
if age >= 18:           # Check if age is greater than or equal to 18 and semicolon is used to end the statement.
    print("You are an adult.")
else:                   # Execute if the condition in the if statement is false.
    print("You are not an adult.")
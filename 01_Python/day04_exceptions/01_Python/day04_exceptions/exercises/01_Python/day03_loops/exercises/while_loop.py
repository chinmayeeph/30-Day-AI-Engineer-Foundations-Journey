# A while loop continues to execute as long as the condition is true.

count = 0                   # Initialize a counter variable.
while count < 5:            # Continue the loop as long as count is less than 5.
    print(count)            # Print the current value of count.
    count += 1              # Increment the counter by 1.
print("Loop has ended.")    # Print a message after the loop has ended.

countdown = 5                   # Initialize a countdown variable.
while countdown > 0:            # Continue the loop as long as countdown is greater than 0.
    print(countdown)            # Print the current value of countdown.
    countdown -= 1              # Decrement the countdown by 1.
print("Blast off!")             # Print "Blast off!" after the countdown is complete.
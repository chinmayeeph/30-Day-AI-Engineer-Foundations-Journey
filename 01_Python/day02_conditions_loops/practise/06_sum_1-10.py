print("-----Exercise 6 — Sum 1–100-----")      # This program calculates the sum of numbers from 1 to 100.
# Initialize a variable to store the sum
sum = 0
for i in range(1, 101):      # Use a for loop to iterate over the range of numbers from 1 to 100 (inclusive).
    sum += i      # Add the current number to the sum.
print("The sum of numbers from 1 to 100 is:", sum)      # Print the final sum after the loop has completed.